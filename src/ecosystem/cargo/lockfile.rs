//! `Cargo.lock`, read for `byrle policy diff`, `explain`, `warm` and `lockfile verify`.
//!
//! A package from crates.io keeps crates.io's source in the file whichever registry
//! replaced it, so the file records no URL a download was fetched from.

use std::collections::BTreeSet;

use serde::Deserialize;

use super::PREFIX;
use super::paths::CRATES;
use crate::identity::Ecosystem;
use crate::lockfile::{Locked, LockedArtifact, Lockfile, Platform, Unread};

/// The lockfile cargo writes, and its readers.
pub const LOCKFILES: &[Lockfile] = &[Lockfile {
    name: "Cargo.lock",
    read: packages,
    artifacts: Some(downloads),
    urls: Some(sources),
    pins: None,
}];

/// File names cargo writes that no reader here takes.
pub const UNREAD: &[Unread] = &[];

/// crates.io's index as `Cargo.lock` writes it, by the git and the sparse protocol.
const CRATES_IO: [&str; 2] = [
    "registry+https://github.com/rust-lang/crates.io-index",
    "sparse+https://index.crates.io/",
];

#[derive(Deserialize)]
struct Lock {
    #[serde(default)]
    package: Vec<Package>,
}

#[derive(Deserialize)]
struct Package {
    name: String,
    version: String,
    /// Absent for a path dependency, the project's own source.
    source: Option<String>,
}

impl Package {
    fn locked(&self) -> Locked {
        (
            Ecosystem::Cargo.as_str().to_owned(),
            self.name.clone(),
            self.version.clone(),
        )
    }

    fn is_crates_io(&self) -> bool {
        self.source
            .as_deref()
            .is_some_and(|source| CRATES_IO.contains(&source))
    }
}

fn lock(text: &str) -> Result<Vec<Package>, String> {
    Ok(toml::from_str::<Lock>(text)
        .map_err(|e| e.to_string())?
        .package)
}

/// Every crates.io package the file locks. Path, git and other registries' are left out.
fn packages(text: &str) -> Result<BTreeSet<Locked>, String> {
    Ok(lock(text)?
        .iter()
        .filter(|package| package.is_crates_io())
        .map(Package::locked)
        .collect())
}

/// For `byrle warm`: each crates.io package's download, at the path the proxy serves it.
fn downloads(text: &str) -> Result<Vec<LockedArtifact>, String> {
    Ok(lock(text)?
        .iter()
        .filter(|package| package.is_crates_io())
        .map(|package| LockedArtifact {
            locked: package.locked(),
            path: format!(
                "{PREFIX}{CRATES}/{}/{}/download",
                package.name, package.version
            ),
            platform: Platform::default(),
            url: None,
        })
        .collect())
}

/// For `byrle lockfile verify`: a crates.io package records no URL; a git or other
/// registry's package is named by its source. A path dependency is the project's own.
fn sources(text: &str) -> Result<Vec<LockedArtifact>, String> {
    let artifacts = downloads(text)?;
    let elsewhere = lock(text)?
        .into_iter()
        .filter(|package| !package.is_crates_io())
        .filter_map(|package| {
            let source = package.source.clone()?;
            Some(LockedArtifact::unregistered(package.locked(), &source))
        });
    Ok(artifacts.into_iter().chain(elsewhere).collect())
}

#[cfg(test)]
#[cfg_attr(coverage_nightly, coverage(off))]
mod tests {
    use super::*;

    /// In cargo 1.99.0's format: crates.io by both protocols, a path, git and another registry.
    const LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "probe"
version = "0.1.0"
dependencies = ["itoa", "local"]

[[package]]
name = "itoa"
version = "1.0.18"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "8f42a60cbdf9a97f5d2305f08a87dc4e09308d1276d28c869c684d7777685682"

[[package]]
name = "Inflector"
version = "0.11.4"
source = "sparse+https://index.crates.io/"
checksum = "fe438567e2a3a2d5a28d0fb8c1a9b8b8b6b6c1c9b8f6b8b8b6b6c1c9b8f6b8b8"

[[package]]
name = "local"
version = "0.1.0"

[[package]]
name = "forked"
version = "0.2.0"
source = "git+https://github.com/example/forked#0123456789abcdef"

[[package]]
name = "internal"
version = "1.0.0"
source = "sparse+https://crates.corp.example/"
"#;

    fn names(found: &[LockedArtifact]) -> Vec<(&str, &str, Option<&str>)> {
        found
            .iter()
            .map(|a| (a.locked.1.as_str(), a.path.as_str(), a.url.as_deref()))
            .collect()
    }

    #[test]
    fn only_crates_io_packages_are_locked_versions() {
        let locked: Vec<Locked> = packages(LOCK).expect("reads").into_iter().collect();
        assert_eq!(
            locked,
            [
                ("cargo".into(), "Inflector".into(), "0.11.4".into()),
                ("cargo".into(), "itoa".into(), "1.0.18".into()),
            ]
        );
    }

    /// The path keeps the published spelling, which static.crates.io needs.
    #[test]
    fn warm_asks_for_each_download_at_the_proxy_s_path() {
        assert_eq!(
            names(&downloads(LOCK).expect("reads")),
            [
                ("itoa", "/cargo/crates/itoa/1.0.18/download", None),
                ("Inflector", "/cargo/crates/Inflector/0.11.4/download", None),
            ]
        );
    }

    /// Where a download came from is cargo's configuration, not the file's.
    #[test]
    fn verify_finds_no_url_for_crates_io_and_names_every_other_source() {
        assert_eq!(
            names(&sources(LOCK).expect("reads")),
            [
                ("itoa", "/cargo/crates/itoa/1.0.18/download", None),
                ("Inflector", "/cargo/crates/Inflector/0.11.4/download", None),
                (
                    "forked",
                    "",
                    Some("git+https://github.com/example/forked#0123456789abcdef")
                ),
                ("internal", "", Some("sparse+https://crates.corp.example/")),
            ]
        );
    }

    #[test]
    fn a_file_that_is_not_toml_is_an_error() {
        for read in [
            |text| packages(text).map(|_| ()),
            |text| downloads(text).map(|_| ()),
            |text| sources(text).map(|_| ()),
        ] {
            assert!(read("[[package]").is_err());
        }
        assert!(packages("version = 4\n").expect("reads").is_empty());
    }
}
